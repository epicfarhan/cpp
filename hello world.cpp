#include <iostream>

int main(){

    // int
    int x;
    x = 5;

    // decimal
    double y = 5.53;

    // strings or characters

    char grade = 'A';

    // boolean

    bool power = false;

    // sting

    std::string name = "farhan";

    std::cout << x << "\n";
    std::cout << y << "\n";
    std::cout << grade << "\n";
    std::cout << power << "\n";
    std::cout << "hello " << name;
    return 0;
}